from app.llm.client import run_tool_call

# Три тест-кейса по заданию:
# (а) точно требует tool — вопрос про конкретный документ в базе
# (б) точно не требует tool — общий вопрос о праве
# (в) пограничный — формулировка, где не очевидно нужен ли tool

TEST_CASES = [
    {
        "label": "а) Требует tool",
        "query": "Найди договор аренды и скажи какой депозит.",
    },
    {
        "label": "б) Не требует tool",
        "query": "Что такое неустойка простыми словами?",
    },
    {
        "label": "в) Пограничный",
        "query": "Есть ли у нас документы про персональные данные?",
    },
]


def main():
    for case in TEST_CASES:
        # Печатаем разделитель и метку кейса
        print("\n" + "=" * 60)
        print(f"КЕЙС: {case['label']}")
        print(f"ЗАПРОС: {case['query']}")
        print("-" * 60)

        # Запускаем полный цикл tool_call
        answer = run_tool_call(case["query"])

        print(f"ОТВЕТ: {answer}")


# if __name__ == "__main__" — скрипт запускается только напрямую,
# не при импорте из другого файла
if __name__ == "__main__":
    main()